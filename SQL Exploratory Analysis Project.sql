-- EXPLORATORY DATA ANALYSIS IN SQL --


-- Database Exploration --

-- Explore All Objects in the Database
SELECT *
FROM INFORMATION_SCHEMA.TABLES

--Explore Columns in the Database
SELECT *
FROM INFORMATION_SCHEMA.COLUMNS

-- Explore the Countries customers come from
SELECT DISTINCT country
FROM gold.dim_customers

-- Explore All Categories/ Major Divisions
SELECT DISTINCT category, subcategory, product_name
FROM gold.dim_products
ORDER BY 1,2,3

-- Exploring Dates --

-- Finding the first and last order date and the years sales are available.
SELECT 
MIN(order_date) AS first_order_date,
MAX(order_date) AS last_order_date,
DATEDIFF(month, MIN(order_date),MAX(order_date)) AS order_range_months
FROM gold.fact_sales

-- Finding the youngest and the oldest customer
SELECT
MIN(birthdate) AS oldest_birthdate,
DATEDIFF(year, MIN(birthdate), GETDATE()) AS oldest_age,
DATEDIFF(year, MAX(birthdate), GETDATE()) AS youngest_age,
MAX(birthdate) AS youngest_birthdate
FROM gold.dim_customers

-- Measures Exploration --

-- Total Sales
SELECT SUM(sales_amount) AS total_sales
FROM gold.fact_sales

-- Amount of Items Sold
SELECT SUM(quantity) AS total_quantity
FROM gold.fact_sales

-- Average Selling Price
SELECT AVG(price) AS avg_price
FROM gold.fact_sales

-- Total # of Orders
SELECT COUNT(order_number) AS total_orders
FROM gold.fact_sales

SELECT COUNT(DISTINCT order_number) AS total_orders
FROM gold.fact_sales

-- Total # of Products
SELECT COUNT(product_name) AS total_products
FROM gold.dim_products

SELECT COUNT(DISTINCT product_name) AS total_products
FROM gold.dim_products

-- Total # of Customers
SELECT COUNT(customer_key) AS total_customers
FROM gold.dim_customers

-- Total # of Customers that Placed an Order
SELECT COUNT(DISTINCT customer_key) AS total_customers
FROM gold.fact_sales

-- Key Metrics Report

SELECT 'Total Sales' as measure_name, SUM(sales_amount) AS measure_value
FROM gold.fact_sales
UNION ALL
SELECT 'Total Quanity', SUM(quantity)
FROM gold.fact_sales
UNION ALL
SELECT 'Average Price', AVG(price)
FROM gold.fact_sales
UNION ALL
SELECT 'Number of Orders', COUNT(DISTINCT order_number)
FROM gold.fact_sales
UNION ALL
SELECT 'Number of Products', COUNT(product_name)
FROM gold.dim_products
UNION ALL
SELECT'Number of Customers', COUNT(customer_key)
FROM gold.dim_customers

-- Magnitude Analysis --

-- Total Customers by Country
SELECT 
country,
COUNT(customer_key) AS total_customers
FROM gold.dim_customers
GROUP BY country
ORDER BY total_customers DESC

-- Total Customers by Gender
SELECT 
gender,
COUNT(customer_key) AS total_customers
FROM gold.dim_customers
GROUP BY gender
ORDER BY total_customers DESC

-- Total Products by Category
SELECT
category,
COUNT(product_key) AS total_products
FROM gold.dim_products
GROUP BY category
ORDER BY total_products DESC

-- Average Cost in Each Category
SELECT
category,
AVG(cost) AS avg_costs
FROM gold.dim_products
GROUP BY category
ORDER BY avg_costs DESC

-- Total Revenue Generated for Each Category
SELECT 
p.category,
SUM(f.sales_amount) total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_products p
ON p.product_key = f.product_key
GROUP BY p.category
ORDER BY total_revenue DESC

-- Total Revenue Generated by Each Customer
SELECT
c.customer_key,
c.first_name,
c.last_name,
SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
ON c.customer_key = f.customer_key
GROUP BY 
c.customer_key,
c.first_name,
c.last_name
ORDER BY total_revenue DESC

-- Distribution of Sold Items Across Countries
SELECT
c.country,
SUM(f.quantity) AS total_sold_items
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
ON c.customer_key = f.customer_key
GROUP BY 
c.country
ORDER BY total_sold_items DESC

-- Ranking Analysis --

-- 5 Products Generating Highest Revenue
SELECT TOP 5
p.subcategory,
SUM(f.sales_amount) total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_products p
ON p.product_key = f.product_key
GROUP BY p.subcategory
ORDER BY total_revenue DESC

SELECT *
FROM (
	SELECT
	p.product_name,
	SUM(f.sales_amount) total_revenue,
	RANK() OVER (ORDER BY SUM(f.sales_amount) DESC) AS rank_products
	FROM gold.fact_sales f
	LEFT JOIN gold.dim_products p
	ON p.product_key = f.product_key
	GROUP BY p.product_name)t
WHERE rank_products <= 5

-- 5 Worst-Performing Products in terms of Sales
SELECT TOP 5
p.product_name,
SUM(f.sales_amount) total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_products p
ON p.product_key = f.product_key
GROUP BY p.product_name
ORDER BY total_revenue

-- Top 10 Customers that Generated Highest Revenue
SELECT TOP 10
c.customer_key,
c.first_name,
c.last_name,
SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
ON c.customer_key = f.customer_key
GROUP BY 
c.customer_key,
c.first_name,
c.last_name
ORDER BY total_revenue DESC

-- 3 Customers with the Fewest Orders
SELECT TOP 3
c.customer_key,
c.first_name,
c.last_name,
COUNT(DISTINCT order_number) AS total_orders
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
ON c.customer_key = f.customer_key
GROUP BY 
c.customer_key,
c.first_name,
c.last_name
ORDER BY total_orders